func (agent *agent) sendPingWorker() {
	Log("agent").Infof("start ping goroutine")
	defer agent.workerWg.Done()

	agent.pingTicker = time.NewTicker(60 * time.Second)
	agent.pingDone = make(chan bool)
	stream := agent.agentGrpc.newPingStreamWithRetry()

	for agent.enable.Load() {
		err := stream.sendPing()
		if err != nil {
			if err != io.EOF {
				Log("agent").Errorf("send ping - %v", err)
			}

			stream.close()
			stream = agent.agentGrpc.newPingStreamWithRetry()
		}

		select {
		case <-agent.pingDone:
			Log("agent").Infof("end ping goroutine")
			stream.close()
			return
		case t := <-agent.pingTicker.C:
			if IsDebugLogLevelEnabled() {
				Log("agent").Debugf("ping at", t)
			}
		}
	}
}

func (agent *agent) sendSpanWorker() {
	Log("agent").Infof("start span goroutine")
	defer agent.workerWg.Done()

	var (
		skipOldSpan  = bool(false)
		skipBaseTime time.Time
	)

	stream := agent.spanGrpc.newSpanStreamWithRetry()
	for chunk := range agent.spanChan {
		if !agent.enable.Load() {
			break
		}

		if skipOldSpan {
			if chunk.span.startTime.Before(skipBaseTime) {
				continue //skip old span
			} else {
				skipOldSpan = false
			}
		}

		err := stream.sendSpan(chunk)
		if err != nil {
			if err != io.EOF {
				Log("agent").Errorf("send span - %v", err)
			}

			stream.close()
			stream = agent.spanGrpc.newSpanStreamWithRetry()

			skipOldSpan = true
			skipBaseTime = time.Now().Add(-time.Second * 1)
		}
	}

	stream.close()
	Log("agent").Infof("end span goroutine")
}

func (agent *agent) sendSpanBatchWorker() {
	Log("agent").Infof("start span batch goroutine")
	defer agent.workerWg.Done()

	// Drain span chunks into unary SendSpanBatch requests.
	// The first chunk starts a batch, collectSpanBatch opportunistically gathers more chunks,
	// and sendSpanBatchAsync hands the batch to a bounded async sender.
	for {
		chunk, ok := <-agent.spanChan
		if !ok {
			break
		}

		batch, closed := agent.spanGrpc.collectSpanBatch(chunk, agent.spanChan)
		agent.spanGrpc.sendSpanBatchAsync(batch)
		if closed {
			break
		}
	}

	// The span channel is closed during shutdown; wait for already accepted async batches
	// before the worker exits so queued spans get the same best-effort flush.
	agent.spanGrpc.awaitInFlightSpanBatch()
	Log("agent").Infof("end span batch goroutine")
}

func (agent *agent) enqueueSpan(span *spanChunk) bool {
	if !agent.enable.Load() {
		return false
	}

	// Fast path keeps enqueue non-blocking while the queue has capacity.
	select {
	case agent.spanChan <- span:
		return true
	default:
		break
	}

	// When the queue is full, discard the oldest span and enqueue the newest so
	// recent traces are favored under backpressure. The mutex makes the
	// drop-then-send pair atomic against other saturated producers; without it,
	// another producer can fill the freed slot between the recv and the send,
	// losing the new span on top of the dropped one. A fast-path send above can
	// still take the slot, but that span was enqueued, so every drop counted
	// below pairs with exactly one successful enqueue.
	agent.spanDropMu.Lock()
	defer agent.spanDropMu.Unlock()

	for agent.enable.Load() {
		select {
		case agent.spanChan <- span:
			return true
		default:
		}

		select {
		case <-agent.spanChan:
			agent.spanDropCount.Add(1)
			if IsDebugLogLevelEnabled() {
				Log("agent").Debugf("discard oldest span queue size:%d", len(agent.spanChan))
			}
		default:
			// the consumer drained the queue between the two selects; resend
		}
	}
	return false
}

func (agent *agent) sendMetaWorker() {
	Log("agent").Infof("start meta goroutine")
	defer agent.workerWg.Done()

	for md := range agent.metaChan {
		if !agent.enable.Load() {
			break
		}

		var success bool
		switch md.(type) {
		case apiMeta:
			api := md.(apiMeta)
			success = agent.agentGrpc.sendApiMetadataWithRetry(api.id, api.descriptor, -1, api.apiType)
			break
		case stringMeta:
			str := md.(stringMeta)
			success = agent.agentGrpc.sendStringMetadataWithRetry(str.id, str.funcName)
			break
		case sqlMeta:
			sql := md.(sqlMeta)
			success = agent.agentGrpc.sendSqlMetadataWithRetry(sql.id, sql.sql)
			break
		case sqlUidMeta:
			sql := md.(sqlUidMeta)
			success = agent.agentGrpc.sendSqlUidMetadataWithRetry(sql.uid, sql.sql)
			break
		case exceptionMeta:
			em := md.(exceptionMeta)
			success = agent.agentGrpc.sendExceptionMetadataWithRetry(&em)
		}

		if !success {
			agent.deleteMetaCache(md)
		}
	}

	Log("agent").Infof("end meta goroutine")
}

func (agent *agent) deleteMetaCache(md interface{}) {
	switch md.(type) {
	case apiMeta:
		api := md.(apiMeta)
		agent.apiCache.Remove(apiCacheKey{api.descriptor, api.apiType})
		break
	case stringMeta:
		agent.errorCache.Remove(md.(stringMeta).funcName)
		break
	case sqlMeta:
		agent.sqlCache.Remove(md.(sqlMeta).sql)
		break
	case sqlUidMeta:
		agent.sqlUidCache.Remove(md.(sqlUidMeta).sql)
		break
	case exceptionMeta:
		break
	}
}

func (agent *agent) tryEnqueueMeta(md interface{}) bool {
	if !agent.enable.Load() {
		return false
	}

	select {
	case agent.metaChan <- md:
		return true
	default:
		break
	}

	select {
	case <-agent.metaChan:
	default:
	}
	return false
}

func (agent *agent) cacheError(errorName string) int32 {
	if !agent.enable.Load() {
		return 0
	}

	if v, ok := agent.errorCache.Peek(errorName); ok {
		return v.(int32)
	}

	id := atomic.AddInt32(&agent.errorIdGen, 1)
	if v, ok, _ := agent.errorCache.PeekOrAdd(errorName, id); ok {
		return v.(int32)
	}

	md := stringMeta{
		id:       id,
		funcName: errorName,
	}
	agent.tryEnqueueMeta(md)

	Log("agent").Infof("cache error id: %d, %s", id, errorName)
	return id
}

func abbreviateString(str string, length int) string {
	if len(str) <= length {
		return str
	}
	return str[:length] + "...(" + fmt.Sprint(length) + ")"
}

func (agent *agent) cacheSql(sql string) int32 {
	if !agent.enable.Load() {
		return 0
	}

	if v, ok := agent.sqlCache.Peek(sql); ok {
		return v.(int32)
	}

	id := atomic.AddInt32(&agent.sqlIdGen, 1)
	if v, ok, _ := agent.sqlCache.PeekOrAdd(sql, id); ok {
		return v.(int32)
	}

	aSql := abbreviateString(sql, maxSqlSize)
	md := sqlMeta{
		id:  id,
		sql: aSql,
	}
	agent.tryEnqueueMeta(md)

	Log("agent").Infof("cache sql id: %d, %s", id, aSql)
	return id
}

func (agent *agent) cacheSqlUid(sql string) []byte {
	if !agent.enable.Load() {
		return nil
	}

	if v, ok := agent.sqlUidCache.Peek(sql); ok {
		return v.([]byte)
	}

	hash := murmur3.New128()
	hash.Write([]byte(sql))
	uid := hash.Sum(nil)
	if v, ok, _ := agent.sqlUidCache.PeekOrAdd(sql, uid); ok {
		return v.([]byte)
	}

	aSql := abbreviateString(sql, maxSqlSize)
	md := sqlUidMeta{
		uid: uid,
		sql: aSql,
	}
	agent.tryEnqueueMeta(md)

	Log("agent").Infof("cache sql uid: %#v, %s", uid, aSql)
	return uid
}

func (agent *agent) cacheSpanApi(descriptor string, apiType int) int32 {
	if !agent.enable.Load() {
		return 0
	}

	key := apiCacheKey{descriptor, apiType}

	if v, ok := agent.apiCache.Peek(key); ok {
		return v.(int32)
	}

	id := atomic.AddInt32(&agent.apiIdGen, 1)
	if v, ok, _ := agent.apiCache.PeekOrAdd(key, id); ok {
		return v.(int32)
	}

	md := apiMeta{
		id:         id,
		descriptor: descriptor,
		apiType:    apiType,
	}
	agent.tryEnqueueMeta(md)

	Log("agent").Infof("cache api id: %d, %s_%d", id, descriptor, apiType)
	return id
}

func (agent *agent) enqueueExceptionMeta(span *span) {
	if !agent.enable.Load() || !span.cfg.errorTraceCallStack {
		return
	}

	md := exceptionMeta{
		txId:       span.txId,
		spanId:     span.spanId,
		exceptions: span.errorChains,
	}
	if span.urlStat != nil {
		md.uriTemplate = span.urlStat.Url
	} else {
		md.uriTemplate = "NULL"
	}

	agent.tryEnqueueMeta(md)
	if IsDebugLogLevelEnabled() {
		Log("agent").Debugf("enqueue exception meta: %v", md)
	}
}

func (agent *agent) enqueueUrlStat(stat *urlStat) bool {
	if !agent.enable.Load() {
		return false
	}

	select {
	case agent.urlStatChan <- stat:
		return true
	default:
		break
	}

	select {
	case <-agent.urlStatChan:
	default:
	}
	if IsTraceLogLevelEnabled() {
		Log("agent").Tracef("url stat channel - max capacity reached or closed")
	}
	return false
}

func (agent *agent) collectUrlStatWorker() {
	Log("agent").Infof("start collect uri stat goroutine")
	defer agent.workerWg.Done()

	agent.initUrlStat()

	for uri := range agent.urlStatChan {
		if !agent.enable.Load() {
			break
		}
		agent.addUrlStatSnapshot(uri)
	}

	Log("agent").Infof("end collect uri stat goroutine")
}

func (agent *agent) sendUrlStatWorker() {
	Log("agent").Infof("start send uri stat goroutine")
	defer agent.workerWg.Done()

	agent.urlStatTicker = time.NewTicker(30 * time.Second)
	agent.urlStatDone = make(chan bool)

	for agent.enable.Load() {
		select {
		case <-agent.urlStatDone:
			Log("agent").Infof("end send uri stat goroutine")
			return
		case <-agent.urlStatTicker.C:
			if agent.config.load().collectUrlStat {
				snapshot := agent.takeUrlStatSnapshot()
				agent.enqueueStat(makePAgentUriStat(snapshot))
			}
		}
	}
}

