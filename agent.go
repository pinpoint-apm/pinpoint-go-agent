type agent struct {
	appName     string
	appType     int32
	agentID     string
	agentName   string
	serviceName string
	objName     *objectName

	startTime   int64
	sequence    int64
	agentGrpc   *agentGrpc
	spanGrpc    *spanGrpc
	statGrpc    *statGrpc
	cmdGrpc     *cmdGrpc
	spanChan    chan *spanChunk
	// spanDropMu serializes the queue-full path of enqueueSpan; spanDropCount
	// counts spans discarded there.
	spanDropMu    sync.Mutex
	spanDropCount atomic.Int64

	metaChan    chan interface{}
	urlStatChan chan *urlStat
	statChan    chan *pb.PStatMessage

	errorCache  *lru.Cache
	errorIdGen  int32
	sqlCache    *lru.Cache
	sqlIdGen    int32
	sqlUidCache *lru.Cache
	apiCache    *lru.Cache
	apiIdGen    int32

	config    *Config
	connectWg sync.WaitGroup
	workerWg  sync.WaitGroup
	enable    atomic.Bool
	shutdown  atomic.Bool

	// stopCtx is cancelled when shutdown begins. The shutdown flag above is
	// only polled, so it cannot wake a goroutine already blocked in a
	// reconnect wait; the context can. Created lazily because the agent is
	// built as a struct literal in several places, including test helpers.
	stopOnce   sync.Once
	stopCtx    context.Context
	stopCancel context.CancelFunc

	// grpcMetaCtx caches the outgoing-metadata context (socketId <= 0), whose
	// headers are immutable for the agent's lifetime, so per-send callers reuse
	// it instead of rebuilding the metadata map on every request.
	grpcMetaOnce sync.Once
	grpcMetaCtx  context.Context

	pingTicker    *time.Ticker
	pingDone      chan bool
	statTicker    *time.Ticker
	statDone      chan bool
	urlStatTicker *time.Ticker
	urlStatDone   chan bool
}

